export const getStoredLanguage = (): SupportedLanguage => {
  try {
    const saved = localStorage.getItem('perkvex_lang') as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }
    // Auto-detect browser language
    const navLang = navigator.language.slice(0, 2).toLowerCase() as SupportedLanguage;
    if (TRANSLATIONS[navLang]) {
      return navLang;
    }
  } catch (e) {
    // ignore
  }
  return 'en';
};

export const setStoredLanguage = (lang: SupportedLanguage) => {
  try {
    localStorage.setItem('perkvex_lang', lang);

    // Apply Google Translate cookies so external synopsis & dynamic content are translated
    const host = window.location.hostname;
    const cookieVal = lang === 'en' ? '' : `/auto/${lang}`;
    document.cookie = `googtrans=${cookieVal}; path=/;`;
    if (host && host.includes('.')) {
      document.cookie = `googtrans=${cookieVal}; path=/; domain=.${host};`;
    }

    // Trigger google translate if widget is present on page
    const selectElem = document.querySelector<HTMLSelectElement>('.goog-te-combo');
    if (selectElem) {
      selectElem.value = lang;
      selectElem.dispatchEvent(new Event('change'));
    }
  } catch (e) {
    console.warn('Language save error', e);
  }
};
